package com.naman.rupeeflow.report

import android.content.Context
import android.content.Intent
import android.graphics.Color
import android.graphics.Paint
import android.graphics.RectF
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import androidx.core.content.FileProvider
import com.naman.rupeeflow.domain.model.PaymentMethod
import com.naman.rupeeflow.domain.model.Transaction
import com.naman.rupeeflow.domain.model.TransactionType
import com.naman.rupeeflow.domain.util.CurrencyUtils
import com.naman.rupeeflow.domain.util.DateTimeUtils
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

data class CategoryReportItem(
    val categoryName: String,
    val amountPaise: Long,
    val percentage: Double,
    val transactionCount: Int
)

data class ExpenseGroupReportItem(
    val groupName: String,
    val amountPaise: Long,
    val transactionCount: Int
)

data class ReportGenerationData(
    val title: String,
    val periodLabel: String,
    val dateRangeLabel: String,
    val transactions: List<Transaction>,
    val totalExpensesPaise: Long,
    val totalIncomePaise: Long,
    val totalRefundsPaise: Long,
    val netSpendingPaise: Long,
    val cashSpendingPaise: Long,
    val onlineSpendingPaise: Long,
    val grossBillsPaise: Long = 0L,
    val categoryBreakdown: List<CategoryReportItem>,
    val expenseGroupBreakdown: List<ExpenseGroupReportItem>
)

object PdfReportGenerator {

    private const val PAGE_WIDTH = 595 // A4 standard point width
    private const val PAGE_HEIGHT = 842 // A4 standard point height
    private const val MARGIN_X = 36f
    private const val MARGIN_TOP = 36f
    private const val MARGIN_BOTTOM = 40f
    private const val USABLE_WIDTH = PAGE_WIDTH - (MARGIN_X * 2)

    fun generatePdf(context: Context, data: ReportGenerationData): File {
        val pdfDocument = PdfDocument()

        val reportsDir = File(context.cacheDir, "reports")
        if (!reportsDir.exists()) reportsDir.mkdirs()
        val file = File(reportsDir, "RupeeFlow_Report_${System.currentTimeMillis()}.pdf")

        // Paints
        val textPaint = Paint().apply {
            isAntiAlias = true
            color = Color.rgb(15, 23, 42) // Dark Navy
            textSize = 10f
        }
        val boldPaint = Paint().apply {
            isAntiAlias = true
            color = Color.rgb(15, 23, 42)
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            textSize = 10f
        }
        val secondaryPaint = Paint().apply {
            isAntiAlias = true
            color = Color.rgb(100, 116, 139) // Slate gray
            textSize = 8.5f
        }
        val titlePaint = Paint().apply {
            isAntiAlias = true
            color = Color.rgb(30, 58, 138) // Deep Blue
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            textSize = 18f
        }
        val sectionHeaderPaint = Paint().apply {
            isAntiAlias = true
            color = Color.rgb(30, 58, 138)
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            textSize = 11f
        }
        val bgCardPaint = Paint().apply {
            isAntiAlias = true
            color = Color.rgb(248, 250, 252) // Very light slate
            style = Paint.Style.FILL
        }
        val cardBorderPaint = Paint().apply {
            isAntiAlias = true
            color = Color.rgb(226, 232, 240)
            style = Paint.Style.STROKE
            strokeWidth = 1f
        }
        val dividerPaint = Paint().apply {
            isAntiAlias = true
            color = Color.rgb(226, 232, 240)
            strokeWidth = 0.8f
        }
        val headerRowBgPaint = Paint().apply {
            isAntiAlias = true
            color = Color.rgb(241, 245, 249)
            style = Paint.Style.FILL
        }

        var pageNumber = 1
        var pageInfo = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, pageNumber).create()
        var currentPage = pdfDocument.startPage(pageInfo)
        var canvas = currentPage.canvas
        var y = MARGIN_TOP

        fun drawFooter() {
            val footerText = "Generated by RupeeFlow on ${SimpleDateFormat("dd MMM yyyy, HH:mm", Locale.getDefault()).format(Date())} • Page $pageNumber"
            secondaryPaint.textAlign = Paint.Align.CENTER
            canvas.drawText(footerText, PAGE_WIDTH / 2f, PAGE_HEIGHT - 18f, secondaryPaint)
            secondaryPaint.textAlign = Paint.Align.LEFT
        }

        fun startNewPage() {
            drawFooter()
            pdfDocument.finishPage(currentPage)
            pageNumber++
            pageInfo = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, pageNumber).create()
            currentPage = pdfDocument.startPage(pageInfo)
            canvas = currentPage.canvas
            y = MARGIN_TOP

            // Draw continuation header
            boldPaint.textSize = 11f
            boldPaint.color = Color.rgb(30, 58, 138)
            canvas.drawText("RupeeFlow Expense Report (Continued)", MARGIN_X, y + 10f, boldPaint)
            boldPaint.textSize = 10f
            boldPaint.color = Color.rgb(15, 23, 42)
            secondaryPaint.textAlign = Paint.Align.RIGHT
            canvas.drawText(data.dateRangeLabel, PAGE_WIDTH - MARGIN_X, y + 10f, secondaryPaint)
            secondaryPaint.textAlign = Paint.Align.LEFT
            y += 20f
            canvas.drawLine(MARGIN_X, y, PAGE_WIDTH - MARGIN_X, y, dividerPaint)
            y += 12f
        }

        // --- PAGE 1: BRAND HEADER ---
        canvas.drawText("RUPEEFLOW", MARGIN_X, y + 14f, titlePaint)
        boldPaint.textSize = 12f
        canvas.drawText(data.title, MARGIN_X, y + 30f, boldPaint)
        boldPaint.textSize = 10f

        secondaryPaint.textAlign = Paint.Align.RIGHT
        canvas.drawText(data.periodLabel.uppercase(), PAGE_WIDTH - MARGIN_X, y + 14f, boldPaint)
        canvas.drawText(data.dateRangeLabel, PAGE_WIDTH - MARGIN_X, y + 28f, secondaryPaint)
        secondaryPaint.textAlign = Paint.Align.LEFT

        y += 44f
        canvas.drawLine(MARGIN_X, y, PAGE_WIDTH - MARGIN_X, y, dividerPaint)
        y += 14f

        // --- SUMMARY KPI CARDS ---
        val cardWidth = (USABLE_WIDTH - 24f) / 4f
        val cardHeight = 44f

        // 1. Personal Expenses
        val card1Rect = RectF(MARGIN_X, y, MARGIN_X + cardWidth, y + cardHeight)
        canvas.drawRoundRect(card1Rect, 6f, 6f, bgCardPaint)
        canvas.drawRoundRect(card1Rect, 6f, 6f, cardBorderPaint)
        canvas.drawText("PERSONAL EXPENSES", MARGIN_X + 8f, y + 14f, secondaryPaint)
        boldPaint.color = Color.rgb(220, 38, 38) // Coral red
        canvas.drawText(CurrencyUtils.formatPaiseToRupees(data.totalExpensesPaise), MARGIN_X + 8f, y + 32f, boldPaint)
        boldPaint.color = Color.rgb(15, 23, 42)

        // 2. Personal Income
        val x2 = MARGIN_X + cardWidth + 8f
        val card2Rect = RectF(x2, y, x2 + cardWidth, y + cardHeight)
        canvas.drawRoundRect(card2Rect, 6f, 6f, bgCardPaint)
        canvas.drawRoundRect(card2Rect, 6f, 6f, cardBorderPaint)
        canvas.drawText("PERSONAL INCOME", x2 + 8f, y + 14f, secondaryPaint)
        boldPaint.color = Color.rgb(16, 185, 129) // Emerald
        canvas.drawText(CurrencyUtils.formatPaiseToRupees(data.totalIncomePaise), x2 + 8f, y + 32f, boldPaint)
        boldPaint.color = Color.rgb(15, 23, 42)

        // 3. Net Personal Spending
        val x3 = x2 + cardWidth + 8f
        val card3Rect = RectF(x3, y, x3 + cardWidth, y + cardHeight)
        canvas.drawRoundRect(card3Rect, 6f, 6f, bgCardPaint)
        canvas.drawRoundRect(card3Rect, 6f, 6f, cardBorderPaint)
        canvas.drawText("NET SPENDING", x3 + 8f, y + 14f, secondaryPaint)
        boldPaint.color = Color.rgb(30, 58, 138)
        canvas.drawText(CurrencyUtils.formatPaiseToRupees(data.netSpendingPaise), x3 + 8f, y + 32f, boldPaint)
        boldPaint.color = Color.rgb(15, 23, 42)

        // 4. Cash vs Online
        val x4 = x3 + cardWidth + 8f
        val card4Rect = RectF(x4, y, x4 + cardWidth, y + cardHeight)
        canvas.drawRoundRect(card4Rect, 6f, 6f, bgCardPaint)
        canvas.drawRoundRect(card4Rect, 6f, 6f, cardBorderPaint)
        canvas.drawText("CASH / ONLINE", x4 + 8f, y + 14f, secondaryPaint)
        val cashSummary = "${CurrencyUtils.formatPaiseToRupees(data.cashSpendingPaise)} / ${CurrencyUtils.formatPaiseToRupees(data.onlineSpendingPaise)}"
        textPaint.textSize = 8.5f
        canvas.drawText(cashSummary, x4 + 8f, y + 32f, textPaint)
        textPaint.textSize = 10f

        y += cardHeight + 14f

        if (data.grossBillsPaise > 0L && data.grossBillsPaise != data.totalExpensesPaise) {
            secondaryPaint.textAlign = Paint.Align.LEFT
            canvas.drawText("Total Group Bills: ${CurrencyUtils.formatPaiseToRupees(data.grossBillsPaise)} • My Allocated Personal Share: ${CurrencyUtils.formatPaiseToRupees(data.totalExpensesPaise)}", MARGIN_X, y, secondaryPaint)
            y += 12f
        } else {
            y += 4f
        }

        // --- CATEGORY BREAKDOWN TABLE ---
        if (data.categoryBreakdown.isNotEmpty()) {
            canvas.drawText("SPENDING BY CATEGORY", MARGIN_X, y + 10f, sectionHeaderPaint)
            y += 18f

            val catTableWidth = USABLE_WIDTH
            val catHeaderRect = RectF(MARGIN_X, y, MARGIN_X + catTableWidth, y + 18f)
            canvas.drawRect(catHeaderRect, headerRowBgPaint)

            boldPaint.textSize = 8.5f
            canvas.drawText("Category", MARGIN_X + 6f, y + 12f, boldPaint)
            canvas.drawText("Txns", MARGIN_X + 220f, y + 12f, boldPaint)
            secondaryPaint.textAlign = Paint.Align.RIGHT
            canvas.drawText("Amount (₹)", MARGIN_X + 380f, y + 12f, boldPaint)
            canvas.drawText("% Share", MARGIN_X + catTableWidth - 6f, y + 12f, boldPaint)
            secondaryPaint.textAlign = Paint.Align.LEFT
            boldPaint.textSize = 10f

            y += 18f

            textPaint.textSize = 8.5f
            data.categoryBreakdown.take(8).forEach { cat ->
                if (y + 16f > PAGE_HEIGHT - MARGIN_BOTTOM) {
                    startNewPage()
                }
                canvas.drawText(cat.categoryName, MARGIN_X + 6f, y + 11f, textPaint)
                canvas.drawText("${cat.transactionCount}", MARGIN_X + 220f, y + 11f, secondaryPaint)
                secondaryPaint.textAlign = Paint.Align.RIGHT
                canvas.drawText(CurrencyUtils.formatPaiseToRupees(cat.amountPaise), MARGIN_X + 380f, y + 11f, textPaint)
                canvas.drawText(String.format(Locale.ROOT, "%.1f%%", cat.percentage), MARGIN_X + catTableWidth - 6f, y + 11f, textPaint)
                secondaryPaint.textAlign = Paint.Align.LEFT
                y += 16f
                canvas.drawLine(MARGIN_X, y, MARGIN_X + catTableWidth, y, dividerPaint)
            }
            textPaint.textSize = 10f
            y += 14f
        }

        // --- EXPENSE GROUP BREAKDOWN TABLE (IF PRESENT) ---
        if (data.expenseGroupBreakdown.isNotEmpty()) {
            if (y + 40f > PAGE_HEIGHT - MARGIN_BOTTOM) {
                startNewPage()
            }
            canvas.drawText("SPENDING BY EXPENSE GROUP / TRIP", MARGIN_X, y + 10f, sectionHeaderPaint)
            y += 18f

            val groupHeaderRect = RectF(MARGIN_X, y, MARGIN_X + USABLE_WIDTH, y + 18f)
            canvas.drawRect(groupHeaderRect, headerRowBgPaint)

            boldPaint.textSize = 8.5f
            canvas.drawText("Expense Group / Trip", MARGIN_X + 6f, y + 12f, boldPaint)
            canvas.drawText("Transactions", MARGIN_X + 260f, y + 12f, boldPaint)
            secondaryPaint.textAlign = Paint.Align.RIGHT
            canvas.drawText("Total Spending", MARGIN_X + USABLE_WIDTH - 6f, y + 12f, boldPaint)
            secondaryPaint.textAlign = Paint.Align.LEFT
            boldPaint.textSize = 10f

            y += 18f
            textPaint.textSize = 8.5f
            data.expenseGroupBreakdown.forEach { eg ->
                if (y + 16f > PAGE_HEIGHT - MARGIN_BOTTOM) {
                    startNewPage()
                }
                canvas.drawText(eg.groupName, MARGIN_X + 6f, y + 11f, textPaint)
                canvas.drawText("${eg.transactionCount}", MARGIN_X + 260f, y + 11f, secondaryPaint)
                secondaryPaint.textAlign = Paint.Align.RIGHT
                canvas.drawText(CurrencyUtils.formatPaiseToRupees(eg.amountPaise), MARGIN_X + USABLE_WIDTH - 6f, y + 11f, textPaint)
                secondaryPaint.textAlign = Paint.Align.LEFT
                y += 16f
                canvas.drawLine(MARGIN_X, y, MARGIN_X + USABLE_WIDTH, y, dividerPaint)
            }
            textPaint.textSize = 10f
            y += 14f
        }

        // --- DETAILED TRANSACTIONS TABLE ---
        if (y + 40f > PAGE_HEIGHT - MARGIN_BOTTOM) {
            startNewPage()
        }

        fun drawTransactionTableHeader() {
            canvas.drawText("TRANSACTION DETAILS (${data.transactions.size} records)", MARGIN_X, y + 10f, sectionHeaderPaint)
            y += 18f

            val txnHeaderRect = RectF(MARGIN_X, y, MARGIN_X + USABLE_WIDTH, y + 18f)
            canvas.drawRect(txnHeaderRect, headerRowBgPaint)

            boldPaint.textSize = 8f
            canvas.drawText("Date", MARGIN_X + 4f, y + 12f, boldPaint)
            canvas.drawText("Title / Merchant", MARGIN_X + 64f, y + 12f, boldPaint)
            canvas.drawText("Category", MARGIN_X + 240f, y + 12f, boldPaint)
            canvas.drawText("Method", MARGIN_X + 340f, y + 12f, boldPaint)
            secondaryPaint.textAlign = Paint.Align.RIGHT
            canvas.drawText("Amount (₹)", MARGIN_X + USABLE_WIDTH - 4f, y + 12f, boldPaint)
            secondaryPaint.textAlign = Paint.Align.LEFT
            boldPaint.textSize = 10f
            y += 18f
        }

        drawTransactionTableHeader()

        textPaint.textSize = 8f
        data.transactions.forEach { txn ->
            if (y + 16f > PAGE_HEIGHT - MARGIN_BOTTOM) {
                startNewPage()
                drawTransactionTableHeader()
            }

            val dateStr = DateTimeUtils.formatDate(txn.transactionDate, "dd/MM/yy")
            val isIncome = txn.transactionType == TransactionType.INCOME || txn.transactionType == TransactionType.REFUND
            val personalExpense = com.naman.rupeeflow.domain.ledger.PersonalFinancialAggregator.calculatePersonalExpense(txn)
            val personalIncome = com.naman.rupeeflow.domain.ledger.PersonalFinancialAggregator.calculatePersonalIncome(txn)
            val personalRefund = com.naman.rupeeflow.domain.ledger.PersonalFinancialAggregator.calculatePersonalRefund(txn)
            val displayPaise = when (txn.transactionType) {
                TransactionType.EXPENSE, TransactionType.UPI_LITE_PAYMENT -> personalExpense
                TransactionType.REFUND -> if (txn.isSplit) personalRefund else txn.amountPaise
                TransactionType.INCOME -> if (txn.isSplit) personalIncome else txn.amountPaise
                else -> txn.amountPaise
            }
            val amountStr = (if (isIncome) "+ " else "- ") + CurrencyUtils.formatPaiseToRupees(displayPaise)
            val titleStr = if (txn.isSplit) {
                "${(txn.merchantName ?: txn.title).take(28)} (Split)"
            } else {
                (txn.merchantName ?: txn.title).take(38)
            }
            val catStr = (txn.category?.name ?: "Other").take(18)
            val methodStr = txn.paymentMethod.displayName.take(12)

            canvas.drawText(dateStr, MARGIN_X + 4f, y + 11f, secondaryPaint)
            canvas.drawText(titleStr, MARGIN_X + 64f, y + 11f, textPaint)
            canvas.drawText(catStr, MARGIN_X + 240f, y + 11f, textPaint)
            canvas.drawText(methodStr, MARGIN_X + 340f, y + 11f, secondaryPaint)

            if (isIncome) {
                boldPaint.color = Color.rgb(16, 185, 129)
            } else {
                boldPaint.color = Color.rgb(220, 38, 38)
            }
            boldPaint.textSize = 8f
            secondaryPaint.textAlign = Paint.Align.RIGHT
            canvas.drawText(amountStr, MARGIN_X + USABLE_WIDTH - 4f, y + 11f, boldPaint)
            secondaryPaint.textAlign = Paint.Align.LEFT
            boldPaint.color = Color.rgb(15, 23, 42)
            boldPaint.textSize = 10f

            y += 16f
            canvas.drawLine(MARGIN_X, y, MARGIN_X + USABLE_WIDTH, y, dividerPaint)
        }

        // Draw footer on the final page
        drawFooter()
        pdfDocument.finishPage(currentPage)

        // Write to output file safely
        FileOutputStream(file).use { out ->
            pdfDocument.writeTo(out)
        }
        pdfDocument.close()

        return file
    }

    fun sharePdf(context: Context, file: File) {
        val uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            file
        )
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "application/pdf"
            putExtra(Intent.EXTRA_STREAM, uri)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        context.startActivity(Intent.createChooser(intent, "Share Expense Report PDF"))
    }
}

